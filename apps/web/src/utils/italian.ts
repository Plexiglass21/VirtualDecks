export function inItalian(message: string): string {
  if (messages[message]) return messages[message]
  const host = message.match(/^(.+) is now the room host\.$/)
  if (host) return `${host[1]} ora è l'host della stanza.`
  const removed = message.match(/^(.+) was removed after being offline too long\.$/)
  if (removed) return `${removed[1]} è stato rimosso dopo una lunga disconnessione.`
  return message
}
